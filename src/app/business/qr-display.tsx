"use client";

import { useEffect, useState } from "react";

interface Qr {
  token: string;
  url: string;
  svg: string;
}

const POLL_MS = 2000;

export function QrDisplay() {
  const [qr, setQr] = useState<Qr | null>(null);

  useEffect(() => {
    let active = true;
    async function load() {
      const res = await fetch("/api/qr", { cache: "no-store" }).catch(() => null);
      if (active && res?.ok) {
        const next: Qr = await res.json();
        setQr((prev) => (prev?.token === next.token ? prev : next));
      }
    }
    load();
    const timer = setInterval(load, POLL_MS);
    return () => {
      active = false;
      clearInterval(timer);
    };
  }, []);

  if (!qr) return <div className="aspect-square w-full max-w-xs animate-pulse rounded-xl bg-stone-200" />;

  return (
    <div className="flex flex-col items-center gap-2">
      {/* The SVG comes from our own API, generated by the qrcode library */}
      <div
        className="w-full max-w-xs rounded-xl bg-white p-3"
        data-testid="qr"
        data-url={qr.url}
        dangerouslySetInnerHTML={{ __html: qr.svg }}
      />
      <a href={qr.url} target="_blank" rel="noreferrer" className="break-all text-xs text-stone-500 underline">
        {qr.url}
      </a>
    </div>
  );
}
